/**
 * Deterministic randomness.
 *
 * Every random draw in the engine comes from ONE master seed (config.seed).
 * Independent sub-streams are derived from it with `fork(label)`, which hashes
 * the master seed together with a stable string label. This matters because:
 *
 *  - the baseline and TARMAC runs consume the *same* patient stream no matter
 *    how many draws each scheduler makes internally, and
 *  - the Monte Carlo predictor can draw freely without perturbing the
 *    "ground truth" of the simulated day.
 *
 * Same seed in => byte-identical output. Math.random() is never used.
 */

/** 32-bit FNV-1a hash of a string, mixed with a numeric seed. */
export function hashSeed(seed: number, label: string): number {
  let h = (0x811c9dc5 ^ (seed >>> 0)) >>> 0;
  for (let i = 0; i < label.length; i++) {
    h ^= label.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  // final avalanche (murmur3 fmix32)
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b) >>> 0;
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35) >>> 0;
  h ^= h >>> 16;
  return h >>> 0;
}

export class Rng {
  private state: number;
  readonly seed: number;

  constructor(seed: number) {
    this.seed = seed >>> 0;
    this.state = this.seed === 0 ? 0x9e3779b9 : this.seed;
  }

  /** Derive an independent, reproducible child stream. */
  fork(label: string): Rng {
    return new Rng(hashSeed(this.seed, label));
  }

  /** mulberry32: uniform float in [0, 1). */
  next(): number {
    let t = (this.state = (this.state + 0x6d2b79f5) >>> 0);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  uniform(min: number, max: number): number {
    return min + (max - min) * this.next();
  }

  /** Integer in [min, max] inclusive. */
  int(min: number, max: number): number {
    return min + Math.floor(this.next() * (max - min + 1));
  }

  chance(p: number): boolean {
    return this.next() < p;
  }

  pick<T>(items: readonly T[]): T {
    return items[Math.floor(this.next() * items.length)];
  }

  /** Standard normal via Box–Muller (one value per call, no caching => simpler determinism). */
  normal(mean = 0, sd = 1): number {
    let u = this.next();
    if (u < 1e-12) u = 1e-12;
    const v = this.next();
    return mean + sd * Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
  }

  /** Exponential with the given rate (events per unit time). */
  exponential(rate: number): number {
    let u = this.next();
    if (u < 1e-12) u = 1e-12;
    return -Math.log(u) / rate;
  }
}

